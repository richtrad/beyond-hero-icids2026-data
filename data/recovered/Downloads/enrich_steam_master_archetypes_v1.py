EXTRA_COLS = [
    "steam_store_url","annotation_status","annotation_priority","annotation_confidence_0_3",
    "annotation_reason","validation_short_description","validation_question_label","needs_human_validation"
]

def parse_year(s):
    if pd.isna(s): return ""
    m = re.search(r"(19|20)\d{2}", str(s))
    return int(m.group(0)) if m else ""

def decade_from_year(y):
    try:
        y=int(float(y))
        return f"{(y//10)*10}s"
    except Exception:
        return ""

def short(s, n=360):
    if pd.isna(s): return ""
    s = re.sub(r"<[^>]+>", " ", str(s))
    s = s.replace("&quot;", '"').replace("&amp;", "&")
    s = re.sub(r"\s+", " ", s).strip()
    return s[:n-1] + "…" if len(s) > n else s

def norm_name(s):
    s=str(s).lower()
    s=re.sub(r"[™®©]", "", s)
    s=re.sub(r"[^a-z0-9]+", " ", s)
    return " ".join(s.split())

def prepare(df):
    for c in EXTRA_COLS:
        if c not in df.columns:
            df[c] = ""
    # Make text/annotation columns object-friendly
    text_cols = [
        "include_in_corpus","exclusion_reason","game_series","protagonist","protagonist_type","protagonist_gender",
        "primary_archetype","secondary_archetype","corpus_notes","coding_source","player_shaped_arc","ensemble_archetypes",
        "llm_primary_archetype_suggestion","llm_secondary_archetype_suggestion","human_validation_primary_mode",
        "human_validation_secondary_mode","human_validation_votes_json","annotation_status","annotation_priority",
        "annotation_reason","validation_short_description","validation_question_label","needs_human_validation"
    ]
    for c in text_cols:
        if c in df.columns:
            df[c] = df[c].astype("object")
    if "original_release_year" not in df.columns:
        df["original_release_year"] = ""
    if "original_release_decade" not in df.columns:
        df["original_release_decade"] = ""
    df["original_release_year"] = df["original_release_year"].replace({np.nan:""})
    if "steam_release_date" in df.columns:
        years = df["steam_release_date"].apply(parse_year)
        empty_year = df["original_release_year"].astype(str).str.strip().eq("")
        df.loc[empty_year, "original_release_year"] = years[empty_year]
    df["original_release_decade"] = df["original_release_year"].apply(decade_from_year)
    df["steam_store_url"] = df["appid"].apply(lambda x: f"https://store.steampowered.com/app/{int(x)}/" if pd.notna(x) else "")
    return df

def apply_mapping(df, idx, data, source_key, applied):
    for key, val in data.items():
        if key in df.columns:
            df.at[idx, key] = val
    if "coding_source" in df.columns:
        df.at[idx, "coding_source"] = "preliminary_manual_llm_assisted_v1"
    df.at[idx, "annotation_status"] = "pre_filled_needs_human_validation"
    df.at[idx, "needs_human_validation"] = "yes"
    if "llm_primary_archetype_suggestion" in df.columns:
        df.at[idx, "llm_primary_archetype_suggestion"] = data.get("primary_archetype", "")
    if "llm_secondary_archetype_suggestion" in df.columns:
        df.at[idx, "llm_secondary_archetype_suggestion"] = data.get("secondary_archetype", "")
    if "llm_shadow_load_suggestion" in df.columns:
        df.at[idx, "llm_shadow_load_suggestion"] = data.get("shadow_load_0_3", "")
    df.at[idx, "annotation_reason"] = data.get("corpus_notes", "")
    applied.append({
        "appid": df.at[idx, "appid"],
        "steam_name": df.at[idx, "steam_name"] if "steam_name" in df.columns else "",
        "source_key": source_key,
        "protagonist": data.get("protagonist", ""),
        "primary_archetype": data.get("primary_archetype", ""),
        "secondary_archetype": data.get("secondary_archetype", ""),
        "confidence": data.get("annotation_confidence_0_3", ""),
    })

def enrich(df):
    df = prepare(df)
    df["name_norm"] = df["steam_name"].fillna(df.get("name_from_app_list","")).apply(norm_name)
    applied = []

    for appid_str, data in EXACT_MAPPINGS.items():
        appid = int(appid_str)
        for idx in df.index[df["appid"] == appid].tolist():
            apply_mapping(df, idx, data, f"appid:{appid}", applied)

    for item in PATTERN_MAPPINGS:
        patt = item["pattern"]
        data = item["data"]
        pnorm = norm_name(patt)
        matches = df.index[df["name_norm"].eq(pnorm) | df["name_norm"].str.contains(re.escape(pnorm), na=False)].tolist()
        for idx in matches:
            if "coding_source" not in df.columns or str(df.at[idx, "coding_source"]).strip() == "":
                apply_mapping(df, idx, data, f"name:{patt}", applied)

    # Prioritize unprocessed rows
    for idx, row in df.iterrows():
        if str(row.get("annotation_status", "")).strip():
            continue
        tags = f"{row.get('steam_categories','')} {row.get('steamspy_tags','')} {row.get('matched_terms','')}".lower()
        ratings = pd.to_numeric(row.get("total_ratings_pos_neg"), errors="coerce")
        rel = pd.to_numeric(row.get("relevance_score"), errors="coerce")
        if pd.isna(ratings): ratings = 0
        if pd.isna(rel): rel = 0
        if ("multiplayer" in tags and "singleplayer" not in tags and ratings >= 50000):
            df.at[idx, "include_in_corpus"] = "no_or_low_priority"
            df.at[idx, "exclusion_reason"] = "Likely multiplayer/systemic with no stable protagonist; review only if needed."
            df.at[idx, "annotation_status"] = "auto_low_priority_no_stable_protagonist"
            df.at[idx, "annotation_priority"] = "D_low"
        elif ratings >= 50000 and ("story rich" in tags or "choices matter" in tags or "rpg" in tags or "adventure" in tags):
            df.at[idx, "include_in_corpus"] = "review"
            df.at[idx, "annotation_status"] = "needs_manual_coding"
            df.at[idx, "annotation_priority"] = "B_high"
            df.at[idx, "needs_human_validation"] = "yes"
        elif ratings >= 10000 and (rel >= 8 or "story rich" in tags or "choices matter" in tags or "rpg" in tags):
            df.at[idx, "include_in_corpus"] = "review"
            df.at[idx, "annotation_status"] = "needs_manual_coding"
            df.at[idx, "annotation_priority"] = "C_medium"
            df.at[idx, "needs_human_validation"] = "yes"
        elif ratings >= 1000 and (rel >= 10 or "story rich" in tags or "choices matter" in tags):
            df.at[idx, "include_in_corpus"] = "review_later"
            df.at[idx, "annotation_status"] = "needs_manual_coding_later"
            df.at[idx, "annotation_priority"] = "C_later"
        else:
            df.at[idx, "annotation_status"] = "unprocessed"
            df.at[idx, "annotation_priority"] = "D_low"

    for idx, row in df.iterrows():
        if row.get("coding_source") == "preliminary_manual_llm_assisted_v1":
            ratings = pd.to_numeric(row.get("total_ratings_pos_neg"), errors="coerce")
            conf = pd.to_numeric(row.get("annotation_confidence_0_3"), errors="coerce")
            if str(row.get("include_in_corpus", "")) == "no_or_low_priority":
                df.at[idx, "annotation_priority"] = "D_low_excluded"
            elif (not pd.isna(ratings) and ratings >= 50000) or (not pd.isna(conf) and conf >= 3):
                df.at[idx, "annotation_priority"] = "A_manual_first"
            else:
                df.at[idx, "annotation_priority"] = "B_mapped"

    for idx, row in df.iterrows():
        title = row.get("steam_name") or row.get("name_from_app_list") or ""
        protagonist = row.get("protagonist") if str(row.get("protagonist","")).strip() else "player character / player role"
        desc = short(row.get("short_description"), 300)
        df.at[idx, "validation_question_label"] = f"{title} — {protagonist}"
        df.at[idx, "validation_short_description"] = f"{title}: {desc}" if desc else f"{title}: classify the main playable character or player role."

    df = df.drop(columns=["name_norm"])
    applied_df = pd.DataFrame(applied)
    if not applied_df.empty:
        applied_df = applied_df.drop_duplicates(subset=["appid","source_key"]).sort_values(["confidence","appid"], ascending=[False, True])
    return df, applied_df

def make_aux_sheets(df, applied_df):
    priority_order = {"A_manual_first":0, "B_high":1, "B_mapped":2, "C_medium":3, "C_later":4, "D_low_excluded":5, "D_low":6}
    df["_prio_sort"] = df["annotation_priority"].map(priority_order).fillna(99)
    df["_rating_sort"] = pd.to_numeric(df["total_ratings_pos_neg"], errors="coerce").fillna(0)
    queue = df[df["annotation_priority"].isin(["A_manual_first","B_high","B_mapped","C_medium","C_later"])].copy()
    queue = queue.sort_values(["_prio_sort","_rating_sort","relevance_score"], ascending=[True,False,False])
    queue_cols = [
        "appid","steam_name","steam_store_url","total_ratings_pos_neg","bucket","matched_terms","annotation_priority",
        "include_in_corpus","protagonist","protagonist_type","protagonist_gender","primary_archetype","secondary_archetype",
        "shadow_load_0_3","player_projection_0_3","narrative_complexity_0_3","player_shaped_arc","ensemble_archetypes",
        "annotation_confidence_0_3","validation_question_label","validation_short_description","corpus_notes","short_description"
    ]
    queue = queue[[c for c in queue_cols if c in queue.columns]]
    summary = pd.DataFrame([
        ["input_rows", len(df)],
        ["pre_filled_rows", int((df["coding_source"]=="preliminary_manual_llm_assisted_v1").sum())],
        ["review_queue_rows", len(queue)],
        ["A_manual_first", int((df["annotation_priority"]=="A_manual_first").sum())],
        ["B_high", int((df["annotation_priority"]=="B_high").sum())],
        ["B_mapped", int((df["annotation_priority"]=="B_mapped").sum())],
        ["C_medium", int((df["annotation_priority"]=="C_medium").sum())],
        ["C_later", int((df["annotation_priority"]=="C_later").sum())],
        ["no_or_low_priority", int((df["include_in_corpus"]=="no_or_low_priority").sum())],
    ], columns=["metric","value"])
    archetypes = pd.DataFrame([
        ["Innocent","Naive, pure, vulnerable, hopeful; often childlike or morally uncorrupted."],
        ["Everyman","Ordinary person, relatable outsider, reluctant participant, worker, citizen, survivor."],
        ["Hero","Struggle, courage, mastery, confrontation, self-overcoming, direct action."],
        ["Caregiver","Protection, healing, responsibility, nurture, rescue, community care."],
        ["Explorer","Journey, discovery, movement through unknown spaces, freedom, curiosity."],
        ["Rebel","Resistance, transgression, revenge, anti-authority, refusal of imposed order."],
        ["Lover","Desire, intimacy, relational identity, devotion, emotional union."],
        ["Creator","Building, crafting, making systems/worlds, invention, expression."],
        ["Jester","Play, chaos, comedy, irreverence, performance, trickster energy."],
        ["Sage","Knowledge, investigation, interpretation, truth-seeking, analysis."],
        ["Magician","Transformation, hidden systems, supernatural/technological power, reality manipulation."],
        ["Ruler","Control, command, governance, order, leadership, systemic responsibility."],
    ], columns=["archetype","working_definition"])
    ptypes = pd.DataFrame([
        ["fixed_protagonist","Named/authored character with stable identity."],
        ["silent_projective_avatar","Playable figure with little/no speech; high player projection."],
        ["custom_protagonist","Player shapes appearance/class/backstory/morality."],
        ["multiple_protagonists","Several authored playable protagonists or selectable origin characters."],
        ["implicit_player_role","No stable fictional protagonist; player inhabits systemic role."],
    ], columns=["protagonist_type","definition"])
    df = df.drop(columns=["_prio_sort","_rating_sort"])
    return queue, summary, archetypes, ptypes

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("input", nargs="?", default="steam_corpus_candidates_master.xlsx")
    ap.add_argument("-o", "--output", default="steam_corpus_annotated_v1.xlsx")
    args = ap.parse_args()

    df = pd.read_excel(args.input)
    df, applied_df = enrich(df)
    queue, summary, archetypes, ptypes = make_aux_sheets(df, applied_df)

    with pd.ExcelWriter(args.output, engine="openpyxl") as writer:
        df.to_excel(writer, sheet_name="CorpusAnnotated", index=False)
        queue.to_excel(writer, sheet_name="CodingQueue", index=False)
        applied_df.to_excel(writer, sheet_name="AppliedMappings", index=False)
        summary.to_excel(writer, sheet_name="Summary", index=False)
        archetypes.to_excel(writer, sheet_name="ArchetypeGuide", index=False)
        ptypes.to_excel(writer, sheet_name="ProtagonistTypes", index=False)

    print(f"Saved {args.output}")
    print(summary.to_string(index=False))

if __name__ == "__main__":
    main()
